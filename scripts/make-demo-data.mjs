#!/usr/bin/env node
// Writes ui/src/demoData.ts: the example the dashboard's introduction lets people try out.
// The data comes from the real engine (scripts/demo.mjs builds the project, this reads its steps),
// so the example always looks like a real project. Run after changing scripts/demo.mjs:
//   npm run build:core && node scripts/make-demo-data.mjs
import { mkdtempSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";
import { spawnSync } from "node:child_process";
import { Scenaria } from "../dist/core/index.js";

const here = dirname(fileURLToPath(import.meta.url));
const tmp = mkdtempSync(join(tmpdir(), "scenaria-demo-data-"));
const env = { ...process.env, SCENARIA_HOME: join(tmp, "home") };
const out = {};
for (const lang of ["de", "en"]) {
  const dir = join(tmp, lang);
  const r = spawnSync(process.execPath, [join(here, "demo.mjs"), dir, "--lang", lang], { env, encoding: "utf8" });
  if (r.status !== 0) throw new Error(r.stderr || r.stdout);
  process.env.SCENARIA_HOME = env.SCENARIA_HOME;
  const s = Scenaria.open(dir);
  const g = s.graph();
  const nodes = g.nodes.map((n, i) => {
    // Nothing of the machine that built it: no ids of a real repository, no user name, no folder.
    const { uid, snapshotFolder, user, createdAt, snapshot, ...rest } = n;
    return { ...rest, ...(snapshot ? { snapshot: { commit: "example", tree: "example", files: snapshot.files } } : {}), minute: i * 7 };
  });
  const asked = {};
  for (const n of g.nodes) {
    const m = { leading: s.messagesLeadingTo(n.id) };
    const u = [...(m.leading ?? [])].reverse().find((x) => x.role === "user");
    if (u) asked[n.id] = u.text;
  }
  out[lang] = { goal: g.root?.goal ?? g.nodes[0].goal ?? "", head: g.state.head, nodes, asked };
}
rmSync(tmp, { recursive: true, force: true });
const file = join(here, "..", "ui", "src", "demoData.ts");
writeFileSync(
  file,
  `// Generated by scripts/make-demo-data.mjs from the real engine — do not edit by hand.\n` +
    `// The example project of the introduction: steps as the engine recorded them, without ids of a machine.\n` +
    `// \`minute\` is the step's distance from the first one; the dashboard turns it into times of today.\n` +
    `export const DEMO_DATA = ${JSON.stringify(out, null, 1)} as const;\n`,
);
console.log(`wrote ${file}`);
